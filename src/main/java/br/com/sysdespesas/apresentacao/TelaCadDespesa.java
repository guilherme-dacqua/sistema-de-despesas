    private void btConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btConfirmarActionPerformed
        
        //Verificar se todos os campos estão preenchidos.
        boolean statusPreench = true;
        if(this.fldDescricao.getText().equals("")){
            this.fldDescricao.setBackground(Color.red);
            statusPreench = false;
        }
        if(this.fldValorParcela.getText().equals("")){
            this.fldValorParcela.setBackground(Color.red);
            statusPreench = false;
        }
        if(this.fldVencimento.getText().equals("")){
            this.fldVencimento.setBackground(Color.red);
            statusPreench = false;
        }
        if(this.fldQntParcelas.getText().equals("")){
            this.fldQntParcelas.setBackground(Color.red);
            statusPreench = false;
        }
        
        if(statusPreench == true){
            //Criar despesa
            String descricao    = this.fldDescricao.getText();
            double valorParcela = Double.parseDouble(this.fldValorParcela.getText());
            String vencimento   = this.fldVencimento.getText();
            int qntParcelas     = Integer.parseInt(this.fldQntParcelas.getText());
            
            new DaoDespesa().create(new Despesa(descricao, valorParcela, vencimento, qntParcelas));
        }
    }//GEN-LAST:event_btConfirmarActionPerformed

